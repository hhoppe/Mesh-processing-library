"""Generate Resample_parity.inc: resizing results of the Python package resampler, asserted by Resample_test.cpp.

Usage: PYTHONPATH=~/proj/resampler python3 -I test/resampler_parity.py > test/Resample_parity.inc
"""

import itertools
import sys

import numpy as np
import resampler

BOUNDARIES = resampler.BOUNDARIES
FILTERS = 'box trapezoid triangle cubic lanczos3 mitchell cardinal3 cardinal5 omoms3 omoms5'.split()
# Source and destination grid types; the pairs other than dual/dual use a subset of the filters and no scaling.
GRIDTYPE_PAIRS = [('dual', 'dual'), ('primal', 'primal'), ('dual', 'primal'), ('primal', 'dual')]
SUBSET_FILTERS = 'box triangle cubic cardinal3 omoms5'.split()
SRC_SIZES = [3, 5]
DST_SIZES = [2, 7]
SCALE_TRANSLATE = [(1.0, 0.0), (0.7, 0.2)]
CVAL = -1.0


def main() -> None:
  sys.stdout.reconfigure(newline='\n')
  print(
      '// Copyright (c) Hugues Hoppe; see LICENSE.\n'
      '// Generated by resampler_parity.py; each line is a resize() result of the Python package resampler.'
  )
  for src_gridtype, dst_gridtype in GRIDTYPE_PAIRS:
    full = src_gridtype == 'dual' and dst_gridtype == 'dual'
    filters = FILTERS if full else SUBSET_FILTERS
    scale_translates = SCALE_TRANSLATE if full else SCALE_TRANSLATE[:1]
    cases = itertools.product(BOUNDARIES, filters, SRC_SIZES, DST_SIZES, scale_translates)
    for boundary, filter, src_size, dst_size, (scale, translate) in cases:
      source = np.arange(src_size, dtype=np.float64) ** 2 / 25.0
      result = resampler.resize(
          source,
          (dst_size,),
          src_gridtype=src_gridtype,
          dst_gridtype=dst_gridtype,
          boundary=boundary,
          cval=CVAL,
          filter=filter,
          scale=scale,
          translate=translate,
      )
      values = ', '.join(repr(float(v)) for v in result)
      print(
          f'check_parity("{boundary}", "{filter}", Gridtype::{src_gridtype}, Gridtype::{dst_gridtype},'
          f' {scale!r}, {translate!r}, {src_size}, {dst_size}, {{{values}}});'
      )


if __name__ == '__main__':
  main()
