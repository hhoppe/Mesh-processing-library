#!/usr/bin/env python3
"""Generate Resample_parity.inc: resizing results of the Python package resampler, asserted by Resample_test.cpp.

Usage: PYTHONPATH=~/proj/resampler python3 -I test/resampler_parity.py > test/Resample_parity.inc
"""

import itertools
import sys

import numpy as np
import resampler

BOUNDARIES = resampler.BOUNDARIES
FILTERS = ['box', 'trapezoid', 'triangle', 'cubic', 'lanczos3', 'mitchell']
GRIDTYPES = ['dual']
SRC_SIZES = [3, 5]
DST_SIZES = [2, 7]
SCALE_TRANSLATE = [(1.0, 0.0), (0.7, 0.2)]
CVAL = -1.0


def main() -> None:
  sys.stdout.reconfigure(newline='\n')
  print(
      '// Generated by resampler_parity.py; each line is a resize() result of the Python package resampler.'
  )
  cases = itertools.product(BOUNDARIES, FILTERS, GRIDTYPES, SRC_SIZES, DST_SIZES, SCALE_TRANSLATE)
  for boundary, filter, gridtype, src_size, dst_size, (scale, translate) in cases:
    source = np.arange(src_size, dtype=np.float64) ** 2 / 25.0
    result = resampler.resize(
        source,
        (dst_size,),
        gridtype=gridtype,
        boundary=boundary,
        cval=CVAL,
        filter=filter,
        scale=scale,
        translate=translate,
    )
    values = ', '.join(repr(float(v)) for v in result)
    print(
        f'check_parity("{boundary}", "{filter}", Gridtype::{gridtype}, {scale!r}, {translate!r},'
        f' {src_size}, {dst_size}, {{{values}}});'
    )


if __name__ == '__main__':
  main()
